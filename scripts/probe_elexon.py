"""Phase 0 recon. Run locally: python scripts/probe_elexon.py  -> writes docs/DATA_FINDINGS.md from REAL responses."""
import json
from pathlib import Path

import httpx

B = "https://data.elexon.co.uk/bmrs/api/v1/datasets"
T = {
    "FUELHH": (f"{B}/FUELHH/stream", {"settlementDateFrom": "2026-01-01", "settlementDateTo": "2026-01-02", "fuelType": "WIND"}),
    "WINDFOR": (f"{B}/WINDFOR/stream", {"publishDateTimeFrom": "2025-12-31T00:00:00Z", "publishDateTimeTo": "2025-12-31T12:00:00Z"}),
}
out = ["# DATA FINDINGS (auto-generated by scripts/probe_elexon.py)\n"]
for name, (url, params) in T.items():
    r = httpx.get(url, params=params, timeout=60)
    out.append(f"## {name}\n- URL: `{r.url}`\n- Status: {r.status_code}\n- Content-Type: {r.headers.get('content-type')}")
    out.append("- Rate-limit/retry headers: " + str({k: v for k, v in r.headers.items() if k.lower().startswith(('x-ratelimit', 'retry'))}))
    try:
        d = r.json()
    except Exception:
        out.append("```\n" + r.text[:500] + "\n```"); continue
    rows = d.get("data", []) if isinstance(d, dict) else d
    out.append(f"- Top-level type: {type(d).__name__}; rows: {len(rows)}")
    if rows:
        out.append(f"- Keys: {sorted(rows[0])}")
        if "publishTime" in rows[0]:
            out.append(f"- Distinct publishTime: {len({x['publishTime'] for x in rows})}; distinct startTime: {len({x['startTime'] for x in rows})}")
        out.append("```json\n" + json.dumps(rows[:3], indent=1) + "\n```")
Path("docs/DATA_FINDINGS.md").write_text("\n".join(out))
print("\n".join(out))
